#!/usr/bin/env python3
"""Write LaTeX macros for the 4 h primary and 6 h sensitivity analyses."""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd


HERE = Path(__file__).resolve().parent
FOUR = HERE / "resolution4h_all15"
SIX = HERE / "results"
FOUR_CHRON = HERE / "chronology_procurement_validation" / "resolution4h_results"
SIX_CHRON = HERE / "chronology_procurement_validation" / "results"
PAIRED = HERE / "resolution4h_vs6h"
OUTPUT = PAIRED / "planning_resolution_macros.tex"


def read(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def fraction(value: int) -> str:
    return f"{value}/15"


def command(name: str, value: object) -> str:
    return rf"\newcommand{{\{name}}}{{{value}}}"


def sci(value: float) -> str:
    mantissa, exponent = f"{value:.2e}".split("e")
    return rf"{mantissa}\times10^{{{int(exponent)}}}"


def main() -> None:
    four = read(FOUR / "headline_metrics.json")
    six = read(SIX / "headline_metrics.json")
    four_qa = read(FOUR / "qa.json")
    six_qa = read(SIX / "qa.json")
    four_chron = read(FOUR_CHRON / "headline_metrics.json")
    six_chron = read(SIX_CHRON / "headline_metrics.json")
    paired = read(PAIRED / "headline_metrics.json")
    paired_pooled = pd.read_csv(PAIRED / "pooled_country_pair.csv")

    lower_cost = {
        risk_weight: int(
            (
                paired_pooled.loc[
                    paired_pooled["risk_weight"].eq(risk_weight),
                    "cost_4h_minus_6h_eur_per_normalized_mw",
                ]
                < 0
            ).sum()
        )
        for risk_weight in (0.0, 0.5)
    }

    lines = [
        "% Generated by write_v62_planning_resolution_macros.py.",
        command("CapFourExpectedMixedCount", fraction(four["expected_cost_mixed_portfolio_countries"])),
        command("CapFourRiskMixedCount", fraction(four["risk_aware_mixed_portfolio_countries"])),
        command("CapFourRiskSetCount", fraction(four["technology_set_change_countries"])),
        command("CapFourRiskDominantCount", fraction(four["dominant_technology_change_countries"])),
        command("CapFourRiskMaterialCount", fraction(four["material_power_change_countries"])),
        command("CapFourRiskMedianAbs", f'{four["median_absolute_procurement_power_shift_percentage_points"]:.2f}'),
        command("CapFourExpectedMenuCount", fraction(four["expected_cost_diversification_improvement_countries"])),
        command("CapFourRiskMenuCount", fraction(four["risk_aware_cvar90_diversification_improvement_countries"])),
        command("CapSixExpectedMixedCount", fraction(six["expected_cost_mixed_portfolio_countries"])),
        command("CapSixRiskMixedCount", fraction(six["risk_aware_mixed_portfolio_countries"])),
        command("CapSixRiskSetCount", fraction(six["technology_set_change_countries"])),
        command("CapSixRiskDominantCount", fraction(six["dominant_technology_change_countries"])),
        command("CapSixRiskMaterialCount", fraction(six["material_power_change_countries"])),
        command("CapSixRiskMedianAbs", f'{six["median_absolute_procurement_power_shift_percentage_points"]:.2f}'),
        command("CapSixExpectedMenuCount", fraction(six["expected_cost_diversification_improvement_countries"])),
        command("CapSixRiskMenuCount", fraction(six["risk_aware_cvar90_diversification_improvement_countries"])),
        command("ChronSixExpectedPowerCount", fraction(six_chron["expected"]["clustered_vs_dispersed_material_power_change_countries"])),
        command("ChronSixRiskPowerCount", fraction(six_chron["mean_cvar90"]["clustered_vs_dispersed_material_power_change_countries"])),
        command("ChronSixExpectedMedianAbsPower", f'{six_chron["expected"]["clustered_vs_dispersed_median_absolute_power_change_pp"]:.2f}'),
        command("ChronSixRiskMedianAbsPower", f'{six_chron["mean_cvar90"]["clustered_vs_dispersed_median_absolute_power_change_pp"]:.2f}'),
        command("ResolutionRiskDirectionAgreement", fraction(paired["risk_pricing"]["direction_agreement_countries"])),
        command("ResolutionExpectedMedianPowerDifference", f'{paired["pooled_capacity"]["expected"]["median_4h_minus_6h_power_pp"]:.2f}'),
        command("ResolutionRiskMedianPowerDifference", f'{paired["pooled_capacity"]["mean_cvar90"]["median_4h_minus_6h_power_pp"]:.2f}'),
        command("ResolutionExpectedActiveSetAgreement", fraction(paired["pooled_capacity"]["expected"]["active_set_agreement_countries"])),
        command("ResolutionRiskActiveSetAgreement", fraction(paired["pooled_capacity"]["mean_cvar90"]["active_set_agreement_countries"])),
        command("ResolutionChronExpectedDirectionAgreement", fraction(paired["chronology_isolation"]["expected"]["clustered_vs_dispersed_direction_agreement_countries"])),
        command("ResolutionChronRiskDirectionAgreement", fraction(paired["chronology_isolation"]["mean_cvar90"]["clustered_vs_dispersed_direction_agreement_countries"])),
        command("ResolutionExpectedLowerCostCount", fraction(lower_cost[0.0])),
        command("ResolutionRiskLowerCostCount", fraction(lower_cost[0.5])),
        command("CapFourObjectiveError", sci(four_qa["maximum_objective_identity_error_eur_per_normalized_mw"])),
        command("CapSixObjectiveError", sci(six_qa["maximum_objective_identity_error_eur_per_normalized_mw"])),
        command("CapFourTaskResidual", sci(four_qa["maximum_task_balance_residual"])),
        command("CapSixTaskResidual", sci(six_qa["maximum_task_balance_residual"])),
        command("CapFourRechargeResidual", sci(four_qa["maximum_shared_recharge_violation"])),
        command("CapSixRechargeResidual", sci(six_qa["maximum_shared_recharge_violation"])),
        command("CapFourSocResidual", sci(four_qa["maximum_state_balance_residual_mwh"])),
        command("CapSixSocResidual", sci(six_qa["maximum_state_balance_residual_mwh"])),
        command("CapFourChronTaskEnergyResidual", sci(four_qa["maximum_chronology_task_energy_residual"])),
        command("CapSixChronTaskEnergyResidual", sci(read(SIX_CHRON / "qa.json")["maximum_chronology_task_energy_residual"])),
        command("CapFourChronRechargeEnergyResidual", sci(four_qa["maximum_chronology_recharge_energy_residual"])),
        command("CapSixChronRechargeEnergyResidual", sci(read(SIX_CHRON / "qa.json")["maximum_chronology_recharge_energy_residual"])),
    ]
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(OUTPUT)


if __name__ == "__main__":
    main()
