#!/usr/bin/env python3
"""Merge QA-passed chronology-procurement shards and rebuild comparisons."""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import sys
from pathlib import Path
from typing import Any

import pandas as pd


HERE = Path(__file__).resolve().parent
RUNNER_PATH = HERE / "run_v62_chronology_procurement_counterfactual.py"
TABLES = (
    "design_summary.csv",
    "capacity_mix.csv",
    "scenario_metrics.csv.gz",
    "chronology_conservation.csv",
)


def load_runner():
    specification = importlib.util.spec_from_file_location(
        "v62_chronology_procurement_runner", RUNNER_PATH
    )
    if specification is None or specification.loader is None:
        raise RuntimeError("Cannot import chronology-procurement runner")
    module = importlib.util.module_from_spec(specification)
    sys.modules[specification.name] = module
    specification.loader.exec_module(module)
    return module


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def write_json(path: Path, value: Any) -> None:
    path.write_text(
        json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )


def write_tex_macros(path: Path, headline: dict[str, Any], capacities: pd.DataFrame) -> None:
    expected = headline["expected"]
    risk = headline["mean_cvar90"]
    hydrogen_nonzero = int(
        capacities.loc[
            capacities["config_id"].astype(str).eq("h2_cavern_168h"),
            "capacity_per_normalized_mw",
        ]
        .abs()
        .gt(1.0e-9)
        .sum()
    )
    design_count = int(
        capacities[["country", "risk_weight", "ensemble"]]
        .drop_duplicates()
        .shape[0]
    )
    lines = [
        "% Generated by merge_v62_chronology_procurement_shards.py.",
        f"\\newcommand{{\\ChronExpectedPowerCount}}{{{expected['clustered_vs_dispersed_material_power_change_countries']}/15}}",
        f"\\newcommand{{\\ChronRiskPowerCount}}{{{risk['clustered_vs_dispersed_material_power_change_countries']}/15}}",
        f"\\newcommand{{\\ChronExpectedSetCount}}{{{expected['clustered_vs_dispersed_technology_set_change_countries']}/15}}",
        f"\\newcommand{{\\ChronRiskSetCount}}{{{risk['clustered_vs_dispersed_technology_set_change_countries']}/15}}",
        f"\\newcommand{{\\ChronExpectedDominantCount}}{{{expected['clustered_vs_dispersed_dominant_technology_change_countries']}/15}}",
        f"\\newcommand{{\\ChronRiskDominantCount}}{{{risk['clustered_vs_dispersed_dominant_technology_change_countries']}/15}}",
        f"\\newcommand{{\\ChronExpectedMedianAbsPower}}{{{expected['clustered_vs_dispersed_median_absolute_power_change_pp']:.2f}}}",
        f"\\newcommand{{\\ChronRiskMedianAbsPower}}{{{risk['clustered_vs_dispersed_median_absolute_power_change_pp']:.2f}}}",
        f"\\newcommand{{\\ChronExpectedMedianMix}}{{{expected['clustered_vs_dispersed_median_mix_total_variation_pp']:.2f}}}",
        f"\\newcommand{{\\ChronRiskMedianMix}}{{{risk['clustered_vs_dispersed_median_mix_total_variation_pp']:.2f}}}",
        f"\\newcommand{{\\ChronExpectedCombinedObservedCount}}{{{expected['combined_vs_observed_material_power_change_countries']}/15}}",
        f"\\newcommand{{\\ChronRiskCombinedObservedCount}}{{{risk['combined_vs_observed_material_power_change_countries']}/15}}",
        f"\\newcommand{{\\ChronDesignCount}}{{{design_count}}}",
        f"\\newcommand{{\\ChronHydrogenNonzeroCount}}{{{hydrogen_nonzero}}}",
    ]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--inputs", nargs="+", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--force", action="store_true")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    output = args.output.resolve()
    if output.exists() and any(output.iterdir()) and not args.force:
        raise RuntimeError("Output directory is non-empty; pass --force to replace")
    output.mkdir(parents=True, exist_ok=True)
    runner = load_runner()

    qa_rows: list[tuple[Path, dict[str, Any]]] = []
    countries_seen: set[str] = set()
    table_frames: dict[str, list[pd.DataFrame]] = {name: [] for name in TABLES}
    for input_dir in args.inputs:
        root = input_dir.resolve()
        qa_path = root / "qa.json"
        qa = json.loads(qa_path.read_text(encoding="utf-8"))
        if qa.get("status") != "pass":
            raise RuntimeError(f"Shard has not passed QA: {root}")
        countries = set(map(str, qa.get("countries", [])))
        overlap = countries_seen & countries
        if overlap:
            raise RuntimeError(f"Countries appear in multiple shards: {sorted(overlap)}")
        countries_seen |= countries
        qa_rows.append((root, qa))
        for name in TABLES:
            table_frames[name].append(pd.read_csv(root / name))

    merged: dict[str, pd.DataFrame] = {}
    for name, frames in table_frames.items():
        frame = pd.concat(frames, ignore_index=True)
        sort_columns = [
            column
            for column in (
                "country",
                "risk_weight",
                "ensemble",
                "mode",
                "year",
                "chronology",
                "config_id",
            )
            if column in frame.columns
        ]
        frame = frame.sort_values(sort_columns, kind="stable").reset_index(drop=True)
        frame.to_csv(output / name, index=False)
        merged[name] = frame

    summaries = merged["design_summary.csv"]
    capacities = merged["capacity_mix.csv"]
    ensemble_comparison, direct_effect, headline = runner.build_comparisons(
        summaries, capacities
    )
    ensemble_comparison.to_csv(output / "ensemble_comparison.csv", index=False)
    direct_effect.to_csv(output / "direct_chronology_effect.csv", index=False)
    runner.write_json(output / "headline_metrics.json", headline)
    write_tex_macros(
        output / "chronology_procurement_macros.tex", headline, capacities
    )

    conservation = merged["chronology_conservation.csv"]
    energy_ranges = conservation.groupby(["country", "year"])[
        ["task_energy_normalized_mwh", "recharge_energy_normalized_mwh"]
    ].agg(lambda values: float(values.max() - values.min()))
    country_specific_input_key = "reused_combined_design_summary"
    input_contracts = {
        json.dumps(
            {
                key: value
                for key, value in qa["input_sha256"].items()
                if key != country_specific_input_key
            },
            sort_keys=True,
        )
        for _, qa in qa_rows
    }
    country_specific_inputs = {
        next(iter(map(str, qa["countries"]))):
            qa["input_sha256"][country_specific_input_key]
        for _, qa in qa_rows
    }
    planning_steps = {int(qa["planning_step_hours"]) for _, qa in qa_rows}
    if len(input_contracts) != 1 or len(planning_steps) != 1:
        raise RuntimeError("Shard input contracts or planning resolutions differ")
    qa = {
        "status": "pass",
        "evidence_status": "merged_chronology_isolated_multiyear_procurement",
        "countries": sorted(countries_seen),
        "country_count": len(countries_seen),
        "ensembles": list(runner.ENSEMBLES),
        "risk_weights": list(runner.RISK_WEIGHTS),
        "planning_step_hours": planning_steps.pop(),
        "all_solver_statuses_optimal": bool(
            summaries["solver_status"].eq("optimal").all()
        ),
        "maximum_objective_identity_error_eur_per_normalized_mw": float(
            summaries["objective_identity_error_eur_per_normalized_mw"].max()
        ),
        "maximum_task_balance_residual": float(
            summaries["maximum_task_balance_residual"].max()
        ),
        "maximum_shared_recharge_violation": float(
            summaries["maximum_shared_recharge_violation"].max()
        ),
        "maximum_state_balance_residual_mwh": float(
            summaries["maximum_state_balance_residual_mwh"].max()
        ),
        "maximum_chronology_task_energy_residual": float(
            energy_ranges["task_energy_normalized_mwh"].max()
        ),
        "maximum_chronology_recharge_energy_residual": float(
            energy_ranges["recharge_energy_normalized_mwh"].max()
        ),
        "input_sha256": json.loads(next(iter(input_contracts))),
        "country_specific_input_sha256": {
            country_specific_input_key: dict(sorted(country_specific_inputs.items()))
        },
        "source_shard_qa_sha256": {
            root.name: sha256(root / "qa.json") for root, _ in qa_rows
        },
    }
    qa["status"] = (
        "pass"
        if qa["all_solver_statuses_optimal"]
        and qa["maximum_objective_identity_error_eur_per_normalized_mw"] <= 0.02
        and qa["maximum_task_balance_residual"] <= 1.0e-6
        and qa["maximum_shared_recharge_violation"] <= 1.0e-6
        and qa["maximum_state_balance_residual_mwh"] <= 1.0e-6
        and qa["maximum_chronology_task_energy_residual"] <= 1.0e-10
        and qa["maximum_chronology_recharge_energy_residual"] <= 1.0e-10
        else "fail"
    )
    output_names = (
        *TABLES,
        "ensemble_comparison.csv",
        "direct_chronology_effect.csv",
        "headline_metrics.json",
        "chronology_procurement_macros.tex",
    )
    qa["output_sha256"] = {
        name: sha256(output / name) for name in output_names
    }
    write_json(output / "qa.json", qa)
    print(json.dumps(qa, ensure_ascii=False, indent=2))
    return 0 if qa["status"] == "pass" else 2


if __name__ == "__main__":
    raise SystemExit(main())
