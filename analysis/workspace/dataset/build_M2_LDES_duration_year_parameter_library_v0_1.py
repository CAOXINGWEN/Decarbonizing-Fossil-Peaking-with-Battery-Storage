#!/usr/bin/env python3
"""Build the unified duration- and year-specific M2 storage parameter library.

This builder retires cost-case labels from the generated outputs. Each
technology-duration-year key has exactly one absolute cost record. The source
M2 v0.7 ``reference`` rows are used only as provenance for the single central
path inherited by non-CAES technologies; ``curve_case`` is not exported.

Outputs
-------
M2_LDES_duration_year_parameter_library_v0_1.csv
    Full technical and economic parameters for every modelled duration and
    every year from 2025 through 2035. Monetary parameters are retained in
    CNY and additionally reported in EUR at one documented reference rate.
M2_LDES_duration_cost_paths_v0_1.csv
    Compact dual-currency absolute-cost table for plotting and economic
    repricing.
M2_LDES_duration_year_parameter_library_v0_1.xlsx
    Workbook containing both tables and metadata.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd


HERE = Path(__file__).resolve().parent
PARAMETER_FILE = HERE / "M2_LDES_technology_parameter_library_v0_2.csv"
LEARNING_FILE = HERE / "M2_LDES_learning_cost_curves_v0_7.csv"
EVIDENCE_FILE = HERE / "M2_LDES_learning_curve_evidence_v0_7.csv"
LFP_OVERRIDE_FILE = HERE / "M2_LFP_duration_cost_overrides_v0_1.csv"
ESGC_FILE = HERE / "ESGC_Cost_Performance_Database_v2024.xlsx"

FULL_OUTPUT = HERE / "M2_LDES_duration_year_parameter_library_v0_1.csv"
COST_OUTPUT = HERE / "M2_LDES_duration_cost_paths_v0_1.csv"
XLSX_OUTPUT = HERE / "M2_LDES_duration_year_parameter_library_v0_1.xlsx"

YEARS = list(range(2025, 2036))
DISCOUNT_RATE = 0.036
USD_TO_CNY = 7.2
CNY_PER_EUR = 8.1185043137255
EUR_PER_CNY = 1.0 / CNY_PER_EUR
FX_REFERENCE_YEAR = 2025
FX_SERIES_KEY = "EXR.A.CNY.EUR.SP00.A"
FX_SOURCE_URL = "https://data.ecb.europa.eu/data/datasets/EXR/EXR.A.CNY.EUR.SP00.A"

MODEL_DURATIONS = {
    "li_lfp": [4, 6, 8, 10],
    "caes": [8, 10, 12, 16, 24],
    "laes": [8, 10, 12, 16, 24],
    "gravity": [8, 10, 12],
    "fecr_flow": [8, 10, 12],
    "molten_salt_tes": [8, 10, 12, 16],
    "vrfb": [4, 6, 8],
    "h2_cavern": [24, 48, 72, 168],
}

# Author-selected all-in 24 h CAES central path. Annual values are generated by
# piecewise compound interpolation so the three anchors remain exact.
CAES_24H_ANCHORS = {2025: 362.259, 2030: 306.0, 2035: 259.0}


def capital_recovery_factor(rate: float, years: int) -> float:
    return float(rate * (1.0 + rate) ** years / ((1.0 + rate) ** years - 1.0))


def piecewise_compound_path(year: int, anchors: dict[int, float]) -> float:
    if year <= 2030:
        fraction = (year - 2025) / 5.0
        return float(anchors[2025] * (anchors[2030] / anchors[2025]) ** fraction)
    fraction = (year - 2030) / 5.0
    return float(anchors[2030] * (anchors[2035] / anchors[2030]) ** fraction)


def cny_to_eur(value: float) -> float:
    """Convert a CNY-denominated value to EUR at the fixed reporting rate."""
    return float(value) * EUR_PER_CNY


def load_caes_esgc_components() -> dict[int, dict[str, float]]:
    database = pd.read_excel(ESGC_FILE, sheet_name="Database")
    use = database[
        database["Technology"].astype(str).eq("CAES")
        & database["Year"].astype(int).eq(2023)
        & database["Power_MW"].astype(float).eq(100.0)
        & database["Estimate_type"].astype(str).eq("Point")
        & database["Duration_hr"].astype(float).isin([10.0, 24.0])
    ].copy()
    parameter_names = {
        "power_cost_cny_kw": "CAES Capital (Turbine, Compressor, BOP, & EPC Management) ($/kW)",
        "energy_cost_cny_kwh": "Cavern Storage ($/kWh)",
        "fixed_om_cny_kw_yr": "Fixed O&M ($/kW-year)",
    }
    result: dict[int, dict[str, float]] = {}
    for duration in [10, 24]:
        sub = use[use["Duration_hr"].astype(float).eq(float(duration))]
        result[duration] = {}
        for field, parameter in parameter_names.items():
            values = sub.loc[sub["Parameter"].astype(str).eq(parameter), "Value"]
            if values.empty:
                raise ValueError(f"Missing ESGC CAES {duration} h parameter: {parameter}")
            result[duration][field] = float(values.iloc[0]) * USD_TO_CNY
    return result


def interpolate_caes_components(duration_h: float, anchors: dict[int, dict[str, float]]) -> dict[str, float]:
    x = np.array([10.0, 24.0])
    return {
        field: float(np.interp(float(duration_h), x, [anchors[10][field], anchors[24][field]]))
        for field in ["power_cost_cny_kw", "energy_cost_cny_kwh", "fixed_om_cny_kw_yr"]
    }


def selected_learning_rows() -> pd.DataFrame:
    learning = pd.read_csv(LEARNING_FILE)
    selected = learning[
        learning["curve_case"].astype(str).eq("reference")
        & learning["learning_year"].astype(int).isin(YEARS)
    ].copy()
    expected = len(MODEL_DURATIONS) * len(YEARS)
    if len(selected) != expected:
        raise ValueError(f"Expected {expected} selected learning rows; found {len(selected)}")
    return selected.drop(columns=["curve_case"])


def evidence_by_technology() -> pd.DataFrame:
    evidence = pd.read_csv(EVIDENCE_FILE)
    sensitivity = evidence["evidence_type"].astype(str).str.contains("sensitivity", case=False, na=False)
    return evidence[~sensitivity].drop_duplicates("tech_id", keep="first").set_index("tech_id")


def build_library() -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    parameters = pd.read_csv(PARAMETER_FILE).set_index("tech_id")
    learning = selected_learning_rows().set_index(["tech_id", "learning_year"])
    evidence = evidence_by_technology()
    lfp_overrides = pd.read_csv(LFP_OVERRIDE_FILE).set_index("duration_h")
    caes_anchors = load_caes_esgc_components()
    caes_24h_esgc = (
        caes_anchors[24]["power_cost_cny_kw"] / 24.0
        + caes_anchors[24]["energy_cost_cny_kwh"]
    )

    full_rows: list[dict[str, object]] = []
    for tech_id, durations in MODEL_DURATIONS.items():
        tech = parameters.loc[tech_id]
        evidence_row = evidence.loc[tech_id] if tech_id in evidence.index else pd.Series(dtype=object)
        for duration_h in durations:
            if duration_h < float(tech["duration_min_h"]) or duration_h > float(tech["duration_max_h"]):
                raise ValueError(f"Duration {duration_h} h outside M2 range for {tech_id}")
            for year in YEARS:
                factors = learning.loc[(tech_id, year)]
                direct_duration_anchor = False
                learning_factor_duration_specific = False

                if tech_id == "li_lfp":
                    if duration_h == 4:
                        total_capex = float(factors["lfp_bess_cost_cny_kwh_reference"])
                        fixed_om = float(tech["fixed_om_cny_kw_yr"])
                        cost_method = "first-paper 4 h all-in LFP path"
                        direct_duration_anchor = True
                        learning_factor_duration_specific = True
                    else:
                        override = lfp_overrides.loc[duration_h]
                        base_capex = float(override["model_capex_cny_kwh_base"])
                        total_capex = base_capex * float(factors["power_cost_factor_vs_2025"])
                        fixed_om = (
                            float(override["model_fixed_om_cny_kw_yr_base"])
                            * float(factors["fixed_om_factor_vs_2025"])
                        )
                        cost_method = "LFP duration override anchor multiplied by unified LFP annual factor"
                        direct_duration_anchor = True
                    power_cost = 0.0
                    energy_cost = total_capex
                elif tech_id == "caes":
                    components = interpolate_caes_components(duration_h, caes_anchors)
                    target_24h = piecewise_compound_path(year, CAES_24H_ANCHORS)
                    scale = target_24h / caes_24h_esgc
                    power_cost = components["power_cost_cny_kw"] * scale
                    energy_cost = components["energy_cost_cny_kwh"] * scale
                    fixed_om = components["fixed_om_cny_kw_yr"]
                    total_capex = power_cost / duration_h + energy_cost
                    cost_method = (
                        "ESGC 100 MW 10/24 h components interpolated by duration and normalized "
                        "to the unified 24 h 362.259/306/259 path"
                    )
                    direct_duration_anchor = duration_h in [10, 24]
                else:
                    power_cost = (
                        float(tech["power_cost_cny_kw_base"])
                        * float(factors["power_cost_factor_vs_2025"])
                    )
                    energy_cost = (
                        float(tech["energy_cost_cny_kwh_base"])
                        * float(factors["energy_cost_factor_vs_2025"])
                    )
                    fixed_om = (
                        float(tech["fixed_om_cny_kw_yr"])
                        * float(factors["fixed_om_factor_vs_2025"])
                    )
                    total_capex = power_cost / duration_h + energy_cost
                    cost_method = (
                        "M2 v0.2 power/energy split evaluated at duration with the single unified annual path"
                    )
                    anchor_duration = evidence_row.get("esgc_duration_h", np.nan)
                    direct_duration_anchor = bool(
                        pd.notna(anchor_duration) and np.isclose(float(anchor_duration), duration_h)
                    )

                variable_om = (
                    float(tech["variable_om_cny_mwh"])
                    * float(factors["variable_om_factor_vs_2025"])
                )
                life_years = int(tech["calendar_life_years"])
                annualized_capex = total_capex * capital_recovery_factor(DISCOUNT_RATE, life_years)
                fixed_cost = annualized_capex + fixed_om / duration_h

                source_key = str(factors.get("source_key", ""))
                if tech_id == "caes":
                    source_key = "PNNL_ESGC_2024_DATABASE;AUTHOR_SELECTED_24H_CAES_PATH"
                elif tech_id == "li_lfp" and duration_h > 4:
                    source_key = "M2_LFP_DURATION_OVERRIDE;FIRST_PAPER_CHINA_LFP_CURVE"

                row = {
                    "library_version": "v0.1",
                    "tech_id": tech_id,
                    "technology_cn": tech["technology_cn"],
                    "technology_en": tech["technology_en"],
                    "family": tech["family"],
                    "model_role": tech["model_role"],
                    "maturity": tech["maturity"],
                    "duration_h": int(duration_h),
                    "learning_year": int(year),
                    "power_cost_cny_kw": power_cost,
                    "power_cost_eur_kw": cny_to_eur(power_cost),
                    "energy_cost_cny_kwh": energy_cost,
                    "energy_cost_eur_kwh": cny_to_eur(energy_cost),
                    "total_capex_cny_kwh": total_capex,
                    "total_capex_eur_kwh": cny_to_eur(total_capex),
                    "annualized_capex_cny_per_kwh_capacity_year": annualized_capex,
                    "annualized_capex_eur_per_kwh_capacity_year": cny_to_eur(annualized_capex),
                    "fixed_om_cny_kw_yr": fixed_om,
                    "fixed_om_eur_kw_yr": cny_to_eur(fixed_om),
                    "variable_om_cny_mwh": variable_om,
                    "variable_om_eur_mwh": cny_to_eur(variable_om),
                    "fixed_cost_cny_per_kwh_capacity_year": fixed_cost,
                    "fixed_cost_eur_per_kwh_capacity_year": cny_to_eur(fixed_cost),
                    "reporting_fx_cny_per_eur": CNY_PER_EUR,
                    "reporting_fx_reference_year": FX_REFERENCE_YEAR,
                    "reporting_fx_series_key": FX_SERIES_KEY,
                    "reporting_fx_source_url": FX_SOURCE_URL,
                    "discount_rate": DISCOUNT_RATE,
                    "capex_power_basis": "discharge power; charge_power_ratio is dispatch-only and is not multiplied into CAPEX",
                    "rte": float(tech["rte_base"]),
                    "self_discharge_pct_day": float(tech["self_discharge_pct_day"]),
                    "calendar_life_years": life_years,
                    "cycle_life_cycles": int(tech["cycle_life_cycles"]),
                    "response_time_min": float(tech["response_time_min"]),
                    "replacement_year": int(tech["replacement_year"]),
                    "replacement_component": tech["replacement_component"],
                    "replacement_fraction_of_component": float(tech["replacement_fraction_of_component"]),
                    "replacement_included_in_fixed_cost": False,
                    "charge_power_ratio": float(tech["charge_power_ratio"]),
                    "cost_derivation_method": cost_method,
                    "evidence_anchor_duration_h": evidence_row.get("esgc_duration_h", 4 if tech_id == "li_lfp" else np.nan),
                    "direct_duration_anchor": direct_duration_anchor,
                    "learning_factor_duration_specific": learning_factor_duration_specific,
                    "source_key": source_key,
                    "primary_source": tech["primary_source"],
                    "parameter_basis": tech["parameter_basis"],
                    "confidence": evidence_row.get("confidence", tech["confidence"]),
                    "notes": tech["notes"],
                    "source_url_primary": factors.get("source_url_primary", tech["source_url_primary"]),
                    "source_url_secondary": factors.get("source_url_secondary", tech["source_url_project"]),
                    "source_url_split": tech["source_url_split"],
                    "source_url_replacement": tech["source_url_replacement"],
                }
                full_rows.append(row)

    full = pd.DataFrame(full_rows).sort_values(["tech_id", "duration_h", "learning_year"])
    cost_columns = [
        "tech_id",
        "technology_en",
        "duration_h",
        "learning_year",
        "power_cost_cny_kw",
        "power_cost_eur_kw",
        "energy_cost_cny_kwh",
        "energy_cost_eur_kwh",
        "total_capex_cny_kwh",
        "total_capex_eur_kwh",
        "annualized_capex_cny_per_kwh_capacity_year",
        "annualized_capex_eur_per_kwh_capacity_year",
        "fixed_om_cny_kw_yr",
        "fixed_om_eur_kw_yr",
        "variable_om_cny_mwh",
        "variable_om_eur_mwh",
        "fixed_cost_cny_per_kwh_capacity_year",
        "fixed_cost_eur_per_kwh_capacity_year",
        "reporting_fx_cny_per_eur",
        "reporting_fx_reference_year",
        "reporting_fx_series_key",
        "reporting_fx_source_url",
        "rte",
        "calendar_life_years",
        "charge_power_ratio",
        "cost_derivation_method",
        "direct_duration_anchor",
        "source_key",
        "confidence",
    ]
    cost = full[cost_columns].copy()
    metadata = pd.DataFrame(
        [
            {"field": "library_scope", "value": "8 technologies; 31 modelled technology-duration pairs; annual 2025-2035"},
            {"field": "unique_key", "value": "tech_id + duration_h + learning_year"},
            {"field": "cost_cases", "value": "none; exactly one absolute path per technology-duration-year"},
            {"field": "discount_rate", "value": DISCOUNT_RATE},
            {"field": "usd_to_cny", "value": USD_TO_CNY},
            {"field": "reporting_fx_cny_per_eur", "value": CNY_PER_EUR},
            {"field": "reporting_fx_eur_per_cny", "value": EUR_PER_CNY},
            {"field": "reporting_fx_reference_year", "value": FX_REFERENCE_YEAR},
            {"field": "reporting_fx_series_key", "value": FX_SERIES_KEY},
            {"field": "reporting_fx_aggregation", "value": "ECB annual average for calendar year 2025"},
            {"field": "reporting_fx_source_url", "value": FX_SOURCE_URL},
            {"field": "caes_24h_anchors_cny_kwh", "value": "2025=362; 2030=306; 2035=259"},
            {
                "field": "caes_24h_anchors_eur_kwh",
                "value": (
                    f"2025={cny_to_eur(362.0):.6f}; "
                    f"2030={cny_to_eur(306.0):.6f}; "
                    f"2035={cny_to_eur(259.0):.6f}"
                ),
            },
            {"field": "replacement_treatment", "value": "parameters retained; replacement not included in reported fixed cost"},
            {"field": "learning_evidence_limit", "value": "absolute costs vary by duration; most future learning rates remain technology-level evidence"},
        ]
    )
    return full, cost, metadata


def validate(full: pd.DataFrame, cost: pd.DataFrame) -> None:
    expected_pairs = sum(len(values) for values in MODEL_DURATIONS.values())
    expected_rows = expected_pairs * len(YEARS)
    if len(full) != expected_rows:
        raise AssertionError(f"Expected {expected_rows} full rows; found {len(full)}")
    if full.duplicated(["tech_id", "duration_h", "learning_year"]).any():
        raise AssertionError("Duplicate technology-duration-year keys")
    if full[["power_cost_cny_kw", "energy_cost_cny_kwh", "total_capex_cny_kwh"]].isna().any().any():
        raise AssertionError("Missing cost value")
    if (full["total_capex_cny_kwh"] <= 0).any():
        raise AssertionError("Non-positive total CAPEX")
    currency_pairs = {
        "power_cost_cny_kw": "power_cost_eur_kw",
        "energy_cost_cny_kwh": "energy_cost_eur_kwh",
        "total_capex_cny_kwh": "total_capex_eur_kwh",
        "annualized_capex_cny_per_kwh_capacity_year": "annualized_capex_eur_per_kwh_capacity_year",
        "fixed_om_cny_kw_yr": "fixed_om_eur_kw_yr",
        "variable_om_cny_mwh": "variable_om_eur_mwh",
        "fixed_cost_cny_per_kwh_capacity_year": "fixed_cost_eur_per_kwh_capacity_year",
    }
    if full[list(currency_pairs) + list(currency_pairs.values())].isna().any().any():
        raise AssertionError("Missing CNY or EUR cost value")
    for cny_column, eur_column in currency_pairs.items():
        expected_eur = full[cny_column] / CNY_PER_EUR
        if not np.allclose(expected_eur, full[eur_column], rtol=1e-12, atol=1e-10):
            raise AssertionError(f"Currency conversion failed for {cny_column} -> {eur_column}")
    if not np.allclose(full["reporting_fx_cny_per_eur"], CNY_PER_EUR, rtol=0.0, atol=1e-12):
        raise AssertionError("Reporting exchange-rate metadata is inconsistent")
    if not full["reporting_fx_reference_year"].eq(FX_REFERENCE_YEAR).all():
        raise AssertionError("Reporting exchange-rate reference year is inconsistent")
    if not full["reporting_fx_series_key"].eq(FX_SERIES_KEY).all():
        raise AssertionError("Reporting exchange-rate series key is inconsistent")
    reconstructed = full["power_cost_cny_kw"] / full["duration_h"] + full["energy_cost_cny_kwh"]
    if not np.allclose(reconstructed, full["total_capex_cny_kwh"], rtol=1e-10, atol=1e-8):
        raise AssertionError("CAPEX split formula failed")
    reconstructed_eur = full["power_cost_eur_kw"] / full["duration_h"] + full["energy_cost_eur_kwh"]
    if not np.allclose(reconstructed_eur, full["total_capex_eur_kwh"], rtol=1e-10, atol=1e-8):
        raise AssertionError("EUR CAPEX split formula failed")
    caes_24 = full[(full["tech_id"] == "caes") & (full["duration_h"] == 24)].set_index("learning_year")
    for year, expected in CAES_24H_ANCHORS.items():
        if not np.isclose(float(caes_24.loc[year, "total_capex_cny_kwh"]), expected, atol=1e-8):
            raise AssertionError(f"CAES 24 h anchor mismatch in {year}")
        expected_eur = cny_to_eur(expected)
        if not np.isclose(float(caes_24.loc[year, "total_capex_eur_kwh"]), expected_eur, atol=1e-8):
            raise AssertionError(f"CAES 24 h EUR anchor mismatch in {year}")
    if len(cost) != len(full):
        raise AssertionError("Compact cost table does not match full library")
    required_cost_columns = list(currency_pairs) + list(currency_pairs.values())
    if any(column not in cost.columns for column in required_cost_columns):
        raise AssertionError("Compact cost table is missing dual-currency fields")


def main() -> None:
    full, cost, metadata = build_library()
    validate(full, cost)
    full.to_csv(FULL_OUTPUT, index=False, encoding="utf-8-sig")
    cost.to_csv(COST_OUTPUT, index=False, encoding="utf-8-sig")
    with pd.ExcelWriter(XLSX_OUTPUT, engine="openpyxl") as writer:
        full.to_excel(writer, sheet_name="parameter_library", index=False)
        cost.to_excel(writer, sheet_name="cost_paths", index=False)
        metadata.to_excel(writer, sheet_name="metadata", index=False)
    print(f"[M2-unified-library] full rows={len(full)} -> {FULL_OUTPUT}")
    print(f"[M2-unified-library] cost rows={len(cost)} -> {COST_OUTPUT}")
    print(f"[M2-unified-library] workbook={XLSX_OUTPUT}")


if __name__ == "__main__":
    main()
